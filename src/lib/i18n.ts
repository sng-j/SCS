/**
 * Inline translation helper for 3 languages.
 * Usage: tx(locale, "English", "한국어", "日本語")
 * Japanese falls back to English if not provided.
 */
export function tx(locale: Locale | string, en: string, ko: string, ja?: string): string {
  if (locale === "ko") return ko !== en ? ko : (KO_DICT[en] || en);
  if (locale === "ja") return ja || JA_DICT[en] || en;
  return en;
}


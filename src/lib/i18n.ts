export function translateNotif(locale: Locale | string, text: string): string {
  for (const p of NOTIF_PATTERNS) {
    const m = text.match(p.pattern);
    if (m) {
      const target = locale === "ko" ? p.ko : locale === "ja" ? p.ja : p.en;
      return target.replace("$1", m[1]);
    }
  }
  return text;
}

export function formError(locale: Locale | string, msg?: string): string {
  if (!msg) return "";
  const entry = FORM_ERRORS[msg];
  if (entry) {
    if (locale === "ko") return entry.ko;
    if (locale === "ja") return entry.ja;
    return entry.en;
  }
  return msg;
}

/**
 * Safe multilingual property accessor for data objects with labelKo/labelEn/labelJa (or titleKo/titleEn etc.)
 * Usage: ml(locale, obj, "title") → obj.titleKo / obj.titleJa / obj.titleEn
 */
export function ml(locale: Locale | string, obj: Record<string, unknown>, prefix: string): string {
  if (locale === "ko") return (obj[`${prefix}Ko`] as string) || (obj[prefix] as string) || "";
  if (locale === "ja") return (obj[`${prefix}Ja`] as string) || (obj[`${prefix}En`] as string) || (obj[prefix] as string) || "";
  return (obj[`${prefix}En`] as string) || (obj[prefix] as string) || "";
}

